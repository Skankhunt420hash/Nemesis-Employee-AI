HTTPS_OK=""; MEINE_IP=""
MEINE_IP=$(curl -s --max-time 3 http://169.254.169.254/metadata/v1/interfaces/public/0/ipv4/address 2>/dev/null)
echo "$MEINE_IP" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' || MEINE_IP=$(curl -s -4 --max-time 6 https://api.ipify.org 2>/dev/null)
echo "$MEINE_IP" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' || MEINE_IP=$(hostname -I 2>/dev/null | awk '{print $1}')

