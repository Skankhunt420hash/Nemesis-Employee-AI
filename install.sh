  DNS_IP=$(getent ahostsv4 "$DOMAIN" 2>/dev/null | awk 'NR==1{print $1}')
  if [ -z "$DNS_IP" ]; then
    nein "$DOMAIN zeigt auf keinen Server. Beim Domain-Anbieter einen A-Eintrag auf $MEINE_IP setzen."
  elif [ -n "$MEINE_IP" ] && [ "$DNS_IP" != "$MEINE_IP" ]; then
    nein "$DOMAIN zeigt auf $DNS_IP, dein Server hat aber $MEINE_IP."
    echo "          -> Beim Domain-Anbieter den A-Eintrag auf $MEINE_IP aendern, dann Installer nochmal."
  else
    ok "$DOMAIN zeigt auf diesen Server ($DNS_IP)"
    NAMEN="$DOMAIN"
    WWW_IP=$(getent ahostsv4 "www.$DOMAIN" 2>/dev/null | awk 'NR==1{print $1}')
    [ "$WWW_IP" = "$DNS_IP" ] && NAMEN="$DOMAIN, www.$DOMAIN"

    BELEGT=$(ss -ltnp 2>/dev/null | grep -E ':(80|443)[[:space:]]' | grep -v '"caddy"')
    if [ -n "$BELEGT" ]; then
      nein "Port 80/443 ist schon von einem anderen Programm belegt:"
      echo "$BELEGT" | sed 's/^/          /'
      echo "          Ich fasse das nicht an. Schick mir diese Zeilen."
    else
      CADDY_NEU=""
      if ! command -v caddy >/dev/null 2>&1; then
        echo "  ...    Installiere Caddy (Webserver mit automatischem Schloss), dauert ca. 1 Minute"
        export DEBIAN_FRONTEND=noninteractive
        apt-get -o DPkg::Lock::Timeout=180 -qq update >/dev/null 2>&1
        apt-get -o DPkg::Lock::Timeout=180 -y -qq install caddy >/dev/null 2>&1
        if ! command -v caddy >/dev/null 2>&1; then
          apt-get -o DPkg::Lock::Timeout=180 -y -qq install debian-keyring debian-archive-keyring apt-transport-https gnupg >/dev/null 2>&1
          curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/gpg.key | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg 2>/dev/null
          curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt > /etc/apt/sources.list.d/caddy-stable.list 2>/dev/null
          apt-get -o DPkg::Lock::Timeout=180 -qq update >/dev/null 2>&1
          apt-get -o DPkg::Lock::Timeout=180 -y -qq install caddy >/dev/null 2>&1
        fi
        CADDY_NEU=1
      fi
      if ! command -v caddy >/dev/null 2>&1; then
        nein "Caddy liess sich nicht installieren"
      else
        ok "Caddy vorhanden"
        CF=/etc/caddy/Caddyfile; mkdir -p /etc/caddy
        [ -f "$CF" ] && cp "$CF" "$BK/Caddyfile.vorher"
        BLOCK=$(printf '# >>> NEMESIS (vom Installer verwaltet)\n%s {\n\tencode gzip\n\treverse_proxy 127.0.0.1:%s\n}\n# <<< NEMESIS' "$NAMEN" "$PORT")
        if [ -n "$CADDY_NEU" ] || [ ! -s "$CF" ]; then
          echo "$BLOCK" > "$CF"
        else
          sed '/# >>> NEMESIS/,/# <<< NEMESIS/d' "$CF" > "$CF.neu"
          printf '\n%s\n' "$BLOCK" >> "$CF.neu"; mv "$CF.neu" "$CF"
        fi
        if caddy validate --config "$CF" --adapter caddyfile >/dev/null 2>&1; then
          if ufw status 2>/dev/null | grep -q "Status: active"; then
            ufw allow 80/tcp >/dev/null 2>&1; ufw allow 443/tcp >/dev/null 2>&1
            ok "Firewall: Port 80 und 443 geoeffnet"
          fi
          systemctl enable caddy >/dev/null 2>&1
          systemctl restart caddy >/dev/null 2>&1
          echo "  ...    Hole das Sicherheits-Zertifikat, bis zu 90 Sekunden"
          for i in $(seq 1 45); do
            sleep 2
            curl -s --max-time 5 --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN/health" 2>/dev/null | grep -q '"ok":true' && { HTTPS_OK=1; break; }
          done
          if [ -n "$HTTPS_OK" ]; then
            ok "https://$DOMAIN laeuft mit Schloss"
          else
            nein "Kein Zertifikat bekommen."
            journalctl -u caddy -n 40 --no-pager 2>/dev/null | grep -iE "error|fail|challenge" | tail -3 | cut -c1-160 | sed 's/^/          /'
            echo "          -> Meist blockt die DigitalOcean-Firewall: Networking -> Firewalls -> 80 und 443 (HTTP/HTTPS) erlauben."
          fi
        else
          nein "Caddy-Konfiguration ungueltig, alte wiederhergestellt"
          [ -f "$BK/Caddyfile.vorher" ] && cp "$BK/Caddyfile.vorher" "$CF"
        fi
      fi
    fi
  fi
fi

